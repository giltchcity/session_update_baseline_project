# Same compile/link recipe (flags.make + link.txt of the stream_4dmap_copy target); only the
# paths are parameterized. The originals write <C>/ours_export(.o) and
# <C>/ours_historical_object_eval into evaluation_complete_20260917 and hardcode
# BUILD=session_update_baseline_project/.../build_canonical.
#   HARNESS_TOOLS_BUILD        CMake build dir that has CMakeFiles/stream_4dmap_copy.dir
#   HARNESS_TOOLS_KHRONOS_EVAL khronos_eval source dir (include/, src/object_evaluator.cpp)
#   HARNESS_TOOLS_BIN          output dir for ours_export / ours_historical_object_eval
#   HARNESS_SYN_SCRIPTS        original script dir (complete_native_export.cpp)
#   HARNESS_HIST_SRC           historical_object_eval.cpp (the file generated by
#                              compile_historical_object_eval.py, kept in the original run dir)
# NOTE: complete_native_export.cpp was edited at 2026-09-17 06:09 to also write <prefix>.rgb
# colour files; the 02:36 ours_export binary used for the published numbers predates that.
# .f32/.u32/meshes.jsonl logic (the only metric inputs) is the same.
from pathlib import Path
import os,shlex,subprocess
BUILD=Path(os.environ['HARNESS_TOOLS_BUILD']);EV=Path(os.environ['HARNESS_TOOLS_KHRONOS_EVAL'])
BIN=Path(os.environ['HARNESS_TOOLS_BIN']);HERE=Path(os.environ['HARNESS_SYN_SCRIPTS']);HIST=Path(os.environ['HARNESS_HIST_SRC'])
assert 'evaluation_complete_20260917' not in str(BIN.resolve()),'refusing to write into the original run directory'
BIN.mkdir(parents=True,exist_ok=True)
target='stream_4dmap_copy'
cm=BUILD/f'CMakeFiles/{target}.dir';flags={}
for line in (cm/'flags.make').read_text().splitlines():
    if line.startswith('CXX_') and ' = ' in line:
        k,v=line.split(' = ',1);flags[k]=shlex.split(v)
# --- compile_complete_exporters.py, method == 'ours' ---
obj=BIN/'ours_export.o'
subprocess.run(['/usr/bin/c++',*flags['CXX_DEFINES'],*flags['CXX_INCLUDES'],'-O2','-std=c++17',
    '-DSYNTHETIC_OURS','-c',str(HERE/'complete_native_export.cpp'),'-o',str(obj)],check=True)
link=shlex.split((cm/'link.txt').read_text());first=next(i for i,x in enumerate(link) if x.endswith('.cpp.o'));link[first]=str(obj)
link[link.index('-o')+1]=str(BIN/'ours_export')
subprocess.run(link,cwd=BUILD,check=True);print('BUILT ours_export',flush=True)
# --- compile_historical_object_eval.py, method == 'ours' ---
link=shlex.split((cm/'link.txt').read_text());tail=link[link.index('-o')+2:]
subprocess.run(['/usr/bin/c++',*flags['CXX_DEFINES'],*flags['CXX_INCLUDES'],'-I'+str(EV/'include'),'-O2','-std=c++17',
    str(HIST),str(EV/'src/object_evaluator.cpp'),'-o',str(BIN/'ours_historical_object_eval'),*tail],cwd=BUILD,check=True)
print('BUILT ours_historical_object_eval',flush=True)
